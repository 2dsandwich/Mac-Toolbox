import AppKit
import Carbon.HIToolbox
import CryptoKit
import Observation

struct Clip: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image }
    var id = UUID()
    var kind: Kind
    var text: String?
    var hasRTF = false
    var hash: String
    var date = Date()
    var sourceBundleID: String?
    var sourceName: String?
    var pinned = false
    var imageSize: [Double]?

    var title: String {
        switch kind {
        case .image:
            if let s = imageSize { return "Image \(Int(s[0]))×\(Int(s[1]))" }
            return "Image"
        case .text:
            let t = text ?? ""
            let line = t.split(whereSeparator: \.isNewline).first.map(String.init) ?? t
            return line.trimmingCharacters(in: .whitespaces)
        }
    }
}

/// Watches the general pasteboard (a cheap change-count check twice a second) and keeps a history on disk.
@MainActor @Observable final class ClipboardStore {
    private(set) var clips: [Clip] = []
    @ObservationIgnored private let store: Store
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var saveScheduled = false
    @ObservationIgnored let dir: URL
    @ObservationIgnored private let thumbs = NSCache<NSString, NSImage>()

    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
    ]

    init(store: Store) {
        self.store = store
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        dir = support.appendingPathComponent("MONEY/Clipboard", isDirectory: true)
        // Moved from the app's earlier names (Flick, then Halo).
        for oldName in ["Halo", "Flick"] {
            let old = support.appendingPathComponent(oldName, isDirectory: true)
            let new = support.appendingPathComponent("MONEY", isDirectory: true)
            if FileManager.default.fileExists(atPath: old.path), !FileManager.default.fileExists(atPath: new.path) {
                try? FileManager.default.moveItem(at: old, to: new)
            }
        }
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        thumbs.countLimit = 60
        if let data = try? Data(contentsOf: indexURL), let saved = try? JSONDecoder().decode([Clip].self, from: data) {
            clips = saved
        }
        if store.settings.skipSecrets {
            let secret = clips.filter { $0.kind == .text && Self.looksSecret($0.text ?? "") }
            if !secret.isEmpty {
                secret.forEach(removeFiles)
                clips.removeAll { c in secret.contains { $0.id == c.id } }
                scheduleSave()
            }
        }
        prune()
    }

    /// API keys, tokens, private keys, 2FA and Wi-Fi secrets never go into the history, alone or inside other text
    /// ("export OPENAI_API_KEY=sk-…", a .env file).
    static func looksSecret(_ raw: String) -> Bool {
        let t = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        let known = [#"\bsk-[A-Za-z0-9_\-]{16,}"#, #"\bsk-ant-"#, #"\b(ghp|gho|ghu|ghs|github_pat)_[A-Za-z0-9_]{20,}"#, #"\bxox[abprs]-"#,
                     #"\bAKIA[0-9A-Z]{16}\b"#, #"-----BEGIN [A-Z ]*PRIVATE KEY-----"#, #"\beyJ[A-Za-z0-9_\-]+\.eyJ[A-Za-z0-9_\-]+\."#,
                     #"\b(sb_secret|sb_publishable|rk_live|sk_live|pk_live|AIza)[A-Za-z0-9_\-]{10,}"#,
                     #"^otpauth(-migration)?://"#, #"^WIFI:.*P:"#]
        if known.contains(where: { t.range(of: $0, options: .regularExpression) != nil }) { return true }
        // A long "word" mixing letters and digits with high randomness, on its own or after KEY= / TOKEN: …
        return t.count <= 20_000 && t.split(whereSeparator: { $0.isWhitespace || $0 == "=" || $0 == "\"" || $0 == "'" }).contains { randomToken(String($0)) }
    }

    private static func randomToken(_ t: String) -> Bool {
        guard (24...400).contains(t.count), !t.contains("://"), !t.contains("@"), !t.contains("/"),
              t.contains(where: \.isNumber), t.contains(where: \.isLetter) else { return false }
        var counts: [Character: Int] = [:]
        t.forEach { counts[$0, default: 0] += 1 }
        let n = Double(t.count)
        let entropy = counts.values.reduce(0.0) { e, c in let p = Double(c) / n; return e - p * log2(p) }
        return entropy > 4.0
    }

    /// Text longer than this (a huge log) isn't kept: every save rewrites the whole history.
    static let maxText = 1_000_000

    private var indexURL: URL { dir.appendingPathComponent("history.json") }
    func imageURL(_ c: Clip) -> URL { dir.appendingPathComponent("\(c.id.uuidString).png") }
    private func rtfURL(_ c: Clip) -> URL { dir.appendingPathComponent("\(c.id.uuidString).rtf") }

    func apply() {
        if store.settings.clipboardEnabled {
            if timer == nil {
                lastChange = NSPasteboard.general.changeCount
                let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
                    MainActor.assumeIsolated { self?.poll() }
                }
                t.tolerance = 0.3
                RunLoop.main.add(t, forMode: .common)
                timer = t
            }
        } else {
            timer?.invalidate()
            timer = nil
        }
        prune()
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        capture(pb)
    }

    private func capture(_ pb: NSPasteboard) {
        let types = pb.types ?? []
        if types.contains(where: { Self.skipTypes.contains($0.rawValue) }) { return }
        let front = NSWorkspace.shared.frontmostApplication
        if let id = front?.bundleIdentifier, store.settings.ignoredApps.contains(id) { return }
        if types.contains(.fileURL) { return } // copied files: not ours to track
        let source = (front?.bundleIdentifier, front?.localizedName)

        if let s = pb.string(forType: .string), s.utf8.count > Self.maxText || (store.settings.skipSecrets && Self.looksSecret(s)) { return }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let rtf = pb.data(forType: .rtf)
            add(Clip(kind: .text, text: s, hasRTF: rtf != nil && rtf!.count < 2_000_000, hash: Self.digest(Data(s.utf8)),
                     sourceBundleID: source.0, sourceName: source.1), rtf: rtf)
        } else if store.settings.saveImages, let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff), raw.count < 40_000_000 {
            let hash = Self.digest(raw)
            if bump(hash: hash) { return }
            Task.detached(priority: .utility) {
                guard let rep = NSBitmapImageRep(data: raw), let png = rep.representation(using: .png, properties: [:]) else { return }
                let size = [Double(rep.pixelsWide), Double(rep.pixelsHigh)]
                await MainActor.run {
                    let clip = Clip(kind: .image, hash: hash, sourceBundleID: source.0, sourceName: source.1, imageSize: size)
                    try? png.write(to: self.imageURL(clip))
                    self.add(clip, rtf: nil)
                }
            }
        }
    }

    private func add(_ clip: Clip, rtf: Data?) {
        if bump(hash: clip.hash) { return }
        if !["Dictation", "Voice Edit"].contains(clip.sourceName ?? "") { Stats.shared.add(.copies) }
        if let rtf, clip.hasRTF { try? rtf.write(to: rtfURL(clip)) }
        clips.insert(clip, at: 0)
        prune()
        scheduleSave()
    }

    /// Moves an existing copy of the same content to the top instead of duplicating it.
    @discardableResult private func bump(hash: String) -> Bool {
        guard let i = clips.firstIndex(where: { $0.hash == hash }) else { return false }
        var c = clips.remove(at: i)
        c.date = Date()
        clips.insert(c, at: 0)
        scheduleSave()
        return true
    }

    /// Puts text on the clipboard and in the history under a source name of our own ("Dictation", "Screen Text").
    func copy(text: String, source: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChange = pb.changeCount
        record(text: text, source: source)
    }

    /// Adds to the history without touching the clipboard.
    func record(text: String, source: String) {
        guard store.settings.clipboardEnabled, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf8.count <= Self.maxText,
              !(store.settings.skipSecrets && Self.looksSecret(text)) else { return }
        add(Clip(kind: .text, text: text, hash: Self.digest(Data(text.utf8)), sourceName: source), rtf: nil)
    }

    /// Ordered for display: pinned first, then newest.
    var ordered: [Clip] { clips.filter(\.pinned) + clips.filter { !$0.pinned } }

    func search(_ q: String) -> [Clip] {
        let all = ordered
        let query = q.trimmingCharacters(in: .whitespaces)
        guard !query.isEmpty else { return all }
        return all.filter { c in
            switch c.kind {
            case .text: (c.text ?? "").localizedCaseInsensitiveContains(query) || (c.sourceName ?? "").localizedCaseInsensitiveContains(query)
            case .image: "image".hasPrefix(query.lowercased()) || (c.sourceName ?? "").localizedCaseInsensitiveContains(query)
            }
        }
    }

    // MARK: Actions

    func write(_ c: Clip, plain: Bool) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch c.kind {
        case .text:
            if !plain, c.hasRTF, let rtf = try? Data(contentsOf: rtfURL(c)) { pb.setData(rtf, forType: .rtf) }
            pb.setString(c.text ?? "", forType: .string)
        case .image:
            if let png = try? Data(contentsOf: imageURL(c)) { pb.setData(png, forType: .png) }
        }
        lastChange = pb.changeCount
        bump(hash: c.hash)
    }

    func togglePin(_ id: UUID) {
        guard let i = clips.firstIndex(where: { $0.id == id }) else { return }
        clips[i].pinned.toggle()
        scheduleSave()
    }

    func delete(_ id: UUID) {
        guard let i = clips.firstIndex(where: { $0.id == id }) else { return }
        removeFiles(clips.remove(at: i))
        scheduleSave()
    }

    func clearAll(keepPinned: Bool) {
        let gone = clips.filter { !keepPinned || !$0.pinned }
        gone.forEach(removeFiles)
        clips.removeAll { !keepPinned || !$0.pinned }
        scheduleSave()
    }

    func thumbnail(_ c: Clip) -> NSImage? {
        let key = c.id.uuidString as NSString
        if let t = thumbs.object(forKey: key) { return t }
        guard let img = NSImage(contentsOf: imageURL(c)) else { return nil }
        thumbs.setObject(img, forKey: key)
        return img
    }

    private func prune() {
        let s = store.settings
        let cutoff = s.clipboardDays > 0 ? Date().addingTimeInterval(-Double(s.clipboardDays) * 86400) : .distantPast
        var kept: [Clip] = []
        var unpinned = 0
        for c in clips {
            if c.pinned { kept.append(c); continue }
            if c.date < cutoff || unpinned >= s.clipboardLimit || (c.kind == .image && !s.saveImages) {
                removeFiles(c)
            } else {
                kept.append(c)
                unpinned += 1
            }
        }
        if kept.count != clips.count {
            clips = kept
            scheduleSave()
        }
    }

    private func removeFiles(_ c: Clip) {
        try? FileManager.default.removeItem(at: imageURL(c))
        try? FileManager.default.removeItem(at: rtfURL(c))
        thumbs.removeObject(forKey: c.id.uuidString as NSString)
    }

    private func scheduleSave() {
        guard !saveScheduled else { return }
        saveScheduled = true
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) { [weak self] in
            MainActor.assumeIsolated {
                guard let self else { return }
                self.saveScheduled = false
                let data = try? JSONEncoder().encode(self.clips)
                let url = self.indexURL
                DispatchQueue.global(qos: .utility).async { try? data?.write(to: url, options: .atomic) }
            }
        }
    }

    static func digest(_ d: Data) -> String {
        SHA256.hash(data: d).map { String(format: "%02x", $0) }.joined()
    }
}

enum Paster {
    static var trusted: Bool { AXIsProcessTrusted() }

    static func requestAccess() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    typealias Saved = [[(NSPasteboard.PasteboardType, Data)]]

    /// Types `text` into the frontmost app by pasting, then puts the previous clipboard back.
    static func pasteText(_ text: String) {
        let (saved, mark) = putOnClipboard(text)
        pressCommandV()
        restore(saved, mark, after: 0.9)
    }

    /// Puts `text` on the clipboard, marked transient so clipboard managers (ours included) skip it. Returns what was
    /// there before and the change count to restore against.
    static func putOnClipboard(_ text: String) -> (Saved, Int) {
        let pb = NSPasteboard.general
        let saved: Saved = (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { t in item.data(forType: t).map { (t, $0) } }
        }
        let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        pb.clearContents()
        pb.declareTypes([.string, transient], owner: nil)
        pb.setString(text, forType: .string)
        pb.setData(Data(), forType: transient)
        return (saved, pb.changeCount)
    }

    static func restore(_ saved: Saved, _ mark: Int, after delay: Double) {
        DispatchQueue.main.asyncAfter(deadline: .now() + delay) {
            let pb = NSPasteboard.general
            guard pb.changeCount == mark, !saved.isEmpty else { return } // something new was copied meanwhile
            pb.clearContents()
            pb.writeObjects(saved.map { pairs in
                let item = NSPasteboardItem()
                for (t, d) in pairs { item.setData(d, forType: t) }
                return item
            })
        }
    }

    enum Delivery: String { case pasted, inserted, typed, unconfirmed, failed }

    /// Pastes `text` into the focused field and checks it arrived. When the field shows no change: in through
    /// Accessibility, then typed. `.failed` leaves `text` on the clipboard. `field` and `post` are for `--paste-test`:
    /// an element of our own, and neither the clipboard nor key events touched.
    static func deliver(_ text: String, pid: pid_t?, field given: AXUIElement? = nil, post: Bool = true) async -> Delivery {
        let look = { given ?? focusedElement(pid).0 }
        let before = look().flatMap(snapshot)
        let (saved, mark) = post ? putOnClipboard(text) : ([], 0)
        if post { pressCommandV() }
        // A field that doesn't say what's in it (terminals, a web view with no tree): nothing to check against, so
        // trust the paste and give a slow app plenty of time to read the clipboard.
        guard let before else {
            Log.write("paste sent, field doesn't tell: not checked")
            restore(saved, mark, after: 4)
            return .unconfirmed
        }
        if await landed(look, before, within: 1.5) {
            Log.write("paste landed")
            restore(saved, mark, after: 0.5)
            return .pasted
        }
        // The paste may still be read late; keep our text there a while so it can't paste the old clipboard.
        Log.write("paste didn't show in the field: inserting through Accessibility")
        if let el = look() {
            let err = AXUIElementSetAttributeValue(el, kAXSelectedTextAttribute as CFString, text as CFString)
            if err == .success, await landed(look, before, within: 0.5) {
                Log.write("inserted through Accessibility")
                restore(saved, mark, after: 4)
                return .inserted
            }
            Log.write("Accessibility insert \(err == .success ? "didn't show" : "refused (\(err.rawValue))"): typing")
        }
        if post {
            await type(text)
            if await landed(look, before, within: 0.8) {
                Log.write("typed \(text.count) chars")
                restore(saved, mark, after: 4)
                return .typed
            }
        }
        Log.write("nothing landed: left on clipboard")
        return .failed
    }

    /// What the field looks like now: its length and where the cursor is. nil when it says neither.
    static func snapshot(_ el: AXUIElement) -> [Int]? {
        var out: [Int] = []
        var n: AnyObject?
        if AXUIElementCopyAttributeValue(el, kAXNumberOfCharactersAttribute as CFString, &n) == .success, let n = n as? Int {
            out.append(n)
        } else if AXUIElementCopyAttributeValue(el, kAXValueAttribute as CFString, &n) == .success, let v = n as? String {
            out.append((v as NSString).length)
        }
        var range: AnyObject?
        if AXUIElementCopyAttributeValue(el, kAXSelectedTextRangeAttribute as CFString, &range) == .success, let r = range,
           CFGetTypeID(r) == AXValueGetTypeID() {
            var cf = CFRange()
            if AXValueGetValue(r as! AXValue, .cfRange, &cf) { out += [cf.location, cf.length] }
        }
        return out.isEmpty ? nil : out
    }

    private static func landed(_ look: () -> AXUIElement?, _ before: [Int], within seconds: Double) async -> Bool {
        let end = Date().addingTimeInterval(seconds)
        repeat {
            try? await Task.sleep(for: .milliseconds(50))
            if let now = look().flatMap(snapshot), now != before { return true }
        } while Date() < end
        return false
    }

    /// The focused element, system-wide, else in app `pid`. Electron apps (ChatGPT, Slack…) report nothing focused
    /// until an assistive app asks for their accessibility tree, so that's asked for first.
    static func focusedElement(_ pid: pid_t?) -> (AXUIElement?, AXError) {
        var focused: AnyObject?
        let system = AXUIElementCreateSystemWide()
        // A busy app would otherwise hold each question for 6 s.
        AXUIElementSetMessagingTimeout(system, 0.5)
        var err = AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focused)
        if err != .success, let pid {
            let app = AXUIElementCreateApplication(pid)
            AXUIElementSetMessagingTimeout(app, 0.5)
            AXUIElementSetAttributeValue(app, "AXManualAccessibility" as CFString, kCFBooleanTrue)
            err = AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &focused)
        }
        guard err == .success, let el = focused, CFGetTypeID(el) == AXUIElementGetTypeID() else { return (nil, err == .success ? .failure : err) }
        AXUIElementSetMessagingTimeout(el as! AXUIElement, 0.5)
        return ((el as! AXUIElement), .success)
    }

    static func hasFocusedWindow(_ pid: pid_t?) -> Bool {
        guard let pid else { return false }
        var w: AnyObject?
        return AXUIElementCopyAttributeValue(AXUIElementCreateApplication(pid), kAXFocusedWindowAttribute as CFString, &w) == .success
    }

    /// `text` in pieces small enough for one key event (it takes 20 UTF-16 units), never splitting a character.
    /// Line breaks are their own piece.
    static func typingChunks(_ text: String) -> [String] {
        var out: [String] = [], cur = ""
        for c in text {
            if c.isNewline {
                if !cur.isEmpty { out.append(cur) }
                out.append("\n")
                cur = ""
            } else if cur.utf16.count + c.utf16.count > 16 {
                out.append(cur)
                cur = String(c)
            } else {
                cur.append(c)
            }
        }
        if !cur.isEmpty { out.append(cur) }
        return out
    }

    /// Types `text` into the frontmost app as key events.
    private static func type(_ text: String) async {
        let src = CGEventSource(stateID: .combinedSessionState)
        for piece in typingChunks(text) {
            let down: CGEvent?, up: CGEvent?
            if piece == "\n" {
                // ⇧Return: a plain Return sends the message in chat apps.
                down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_Return), keyDown: true)
                up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_Return), keyDown: false)
                down?.flags = .maskShift
                up?.flags = .maskShift
            } else {
                let units = Array(piece.utf16)
                down = CGEvent(keyboardEventSource: src, virtualKey: 0, keyDown: true)
                up = CGEvent(keyboardEventSource: src, virtualKey: 0, keyDown: false)
                for e in [down, up] {
                    e?.flags = [] // a held modifier would make it a shortcut
                    e?.keyboardSetUnicodeString(stringLength: units.count, unicodeString: units)
                }
            }
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
            try? await Task.sleep(for: .milliseconds(8))
        }
    }

    /// Sends ⌘C and returns what the frontmost app copied, restoring the clipboard after.
    static func copySelection() async -> String? {
        let pb = NSPasteboard.general
        let saved: [[(NSPasteboard.PasteboardType, Data)]] = (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { t in item.data(forType: t).map { (t, $0) } }
        }
        let before = pb.changeCount
        let src = CGEventSource(stateID: .combinedSessionState)
        let c = CGKeyCode(kVK_ANSI_C)
        let down = CGEvent(keyboardEventSource: src, virtualKey: c, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: c, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
        for _ in 0..<12 {
            try? await Task.sleep(for: .milliseconds(25))
            if pb.changeCount != before { break }
        }
        guard pb.changeCount != before else { return nil }
        let text = pb.string(forType: .string)
        pb.clearContents()
        if !saved.isEmpty {
            pb.writeObjects(saved.map { pairs in
                let item = NSPasteboardItem()
                for (t, d) in pairs { item.setData(d, forType: t) }
                return item
            })
        }
        return text
    }

    /// Sends ⌘V to the frontmost app.
    static func pressCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let v = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
